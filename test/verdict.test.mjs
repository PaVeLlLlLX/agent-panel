/**
 * Разбор вердикта рецензента.
 *
 * Зачем. В живом прогоне автоматические раунды заканчивались только по счёту:
 * три раунда прошли, предел сработал, а проверка, поставленная посреди
 * обмена, осталась без ответа. Обмен должен заканчиваться по ИТОГУ —
 * рецензент либо принял работу, либо нет. Для этого вердикт нужно
 * извлекать из ответа надёжно, а ошибиться здесь дороже, чем промолчать:
 * принятое по ошибке «ПРИНЯТО» остановит проверку, которая не прошла.
 */
import { test } from "node:test";
import assert from "node:assert/strict";

import { parseVerdict } from "../out/verdict.js";

test("строка ВЕРДИКТ: ПРИНЯТО в конце — принято", () => {
  assert.equal(
    parseVerdict("Проверил вывод тестов, расхождений нет.\n\nВЕРДИКТ: ПРИНЯТО"),
    "accepted",
  );
});

test("строка ВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ — замечания", () => {
  assert.equal(
    parseVerdict("Есть два дефекта.\nВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ"),
    "remarks",
  );
});

test("разметка markdown вокруг вердикта не мешает", () => {
  assert.equal(parseVerdict("Итог.\n**ВЕРДИКТ: ПРИНЯТО**"), "accepted");
  assert.equal(parseVerdict("Итог.\n> `ВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ`"), "remarks");
});

test("регистр не важен", () => {
  assert.equal(parseVerdict("вердикт: принято"), "accepted");
});

test("отрицание не принимается за согласие", () => {
  // «НЕ ПРИНЯТО» содержит «ПРИНЯТ». Наивный поиск подстроки остановил бы
  // проверку, которая как раз не прошла.
  assert.equal(parseVerdict("ВЕРДИКТ: НЕ ПРИНЯТО"), "remarks");
});

test("без строки вердикта — вердикт отсутствует", () => {
  assert.equal(parseVerdict("Выглядит неплохо, но я не уверен."), "missing");
});

test("вердикт, упомянутый внутри фразы, не считается вынесенным", () => {
  // Рецензент может процитировать инструкцию. Цитата — не решение.
  assert.equal(
    parseVerdict("Мне сказали закончить строкой `ВЕРДИКТ: ПРИНЯТО`, но пока рано."),
    "missing",
  );
});

test("действует последний вердикт", () => {
  assert.equal(
    parseVerdict(
      "Сначала думал так:\nВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ\nПерепроверил — ошибся.\nВЕРДИКТ: ПРИНЯТО",
    ),
    "accepted",
  );
});

test("нераспознанное значение — вердикт отсутствует, а не согласие", () => {
  assert.equal(parseVerdict("ВЕРДИКТ: подумаю ещё"), "missing");
});

test("пустой и отсутствующий текст — вердикт отсутствует", () => {
  assert.equal(parseVerdict(""), "missing");
  assert.equal(parseVerdict(undefined), "missing");
});
