/**
 * Разбор вердикта рецензента.
 *
 * Ошибка разбора несимметрична: ложное «принято» останавливает проверку,
 * которая не прошла, а ложное «вердикта нет» лишь просит решения человека.
 * Поэтому правило строгое: вердикт засчитывается, только если это ПОСЛЕДНЯЯ
 * содержательная строка ответа, вне цитаты и блока кода, и значение точно
 * одно из двух. Всё прочее — «вердикта нет».
 *
 * Первая версия засчитывала подстроку «ПРИНЯТ» в любой строке, начинающейся
 * с «ВЕРДИКТ». Рецензент нашёл два случая, где это даёт «принято» ложно:
 * слитное «НЕПРИНЯТО» и цитату прежнего вердикта. Оба воспроизведены.
 */
import { test } from "node:test";
import assert from "node:assert/strict";

import { parseVerdict } from "../out/verdict.js";

test("последняя строка ВЕРДИКТ: ПРИНЯТО — принято", () => {
  assert.equal(
    parseVerdict("Проверил вывод тестов, расхождений нет.\n\nВЕРДИКТ: ПРИНЯТО"),
    "accepted",
  );
});

test("последняя строка ВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ — замечания", () => {
  assert.equal(parseVerdict("Есть два дефекта.\nВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ"), "remarks");
});

test("выделение жирным и точка в конце не мешают", () => {
  assert.equal(parseVerdict("Итог.\n**ВЕРДИКТ: ПРИНЯТО**"), "accepted");
  assert.equal(parseVerdict("Итог.\nВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ."), "remarks");
});

test("регистр не важен", () => {
  assert.equal(parseVerdict("вердикт: принято"), "accepted");
});

test("слитное НЕПРИНЯТО — не согласие", () => {
  // Воспроизведено рецензентом: прежний разбор давал «принято».
  assert.equal(parseVerdict("ВЕРДИКТ: НЕПРИНЯТО"), "missing");
});

test("НЕ ПРИНЯТО — не согласие", () => {
  assert.equal(parseVerdict("ВЕРДИКТ: НЕ ПРИНЯТО"), "missing");
});

test("цитата прежнего вердикта — не решение", () => {
  // Воспроизведено рецензентом: прежний разбор давал «принято».
  assert.equal(
    parseVerdict("> ВЕРДИКТ: ПРИНЯТО\nЭто цитата прежнего ответа. Проверка ещё не завершена."),
    "missing",
  );
});

test("цитата вердикта последней строкой — тоже не решение", () => {
  assert.equal(parseVerdict("Прошлый раз было так:\n> ВЕРДИКТ: ПРИНЯТО"), "missing");
});

test("вердикт внутри блока кода — не решение", () => {
  assert.equal(parseVerdict("Пример формата:\n```\nВЕРДИКТ: ПРИНЯТО\n```"), "missing");
});

test("вердикт не последней строкой — не решение", () => {
  assert.equal(parseVerdict("ВЕРДИКТ: ПРИНЯТО\nНо ещё посмотрю один файл."), "missing");
});

test("действует последний вердикт, если он последняя строка", () => {
  assert.equal(
    parseVerdict(
      "Сначала думал так:\nВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ\nПерепроверил — ошибся.\nВЕРДИКТ: ПРИНЯТО",
    ),
    "accepted",
  );
});

test("вердикт, упомянутый внутри фразы, — не решение", () => {
  assert.equal(
    parseVerdict("Мне сказали закончить строкой `ВЕРДИКТ: ПРИНЯТО`, но пока рано."),
    "missing",
  );
});

test("нераспознанное значение — вердикта нет", () => {
  assert.equal(parseVerdict("ВЕРДИКТ: подумаю ещё"), "missing");
});

test("пустые строки в конце не мешают", () => {
  assert.equal(parseVerdict("Итог.\nВЕРДИКТ: ПРИНЯТО\n\n  \n"), "accepted");
});

test("пустой и отсутствующий текст — вердикта нет", () => {
  assert.equal(parseVerdict(""), "missing");
  assert.equal(parseVerdict(undefined), "missing");
});
