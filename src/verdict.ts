/**
 * Вердикт рецензента: чем заканчивается цикл проверки.
 *
 * В живом прогоне раунды заканчивались только по счёту, и проверка,
 * поставленная посреди обмена, осталась без ответа. Цикл должен кончаться
 * по итогу. Ошибка разбора здесь несимметрична: ложное «принято» останавливает
 * проверку, которая не прошла, поэтому всё нераспознанное — «вердикта нет».
 */

export type Verdict = "accepted" | "remarks" | "missing";

/** Добавляется к каждому запросу на проверку. */
export const VERDICT_REQUEST =
  "Завершите ответ отдельной строкой: «ВЕРДИКТ: ПРИНЯТО», если существенных " +
  "замечаний нет, или «ВЕРДИКТ: ЕСТЬ ЗАМЕЧАНИЯ», если они есть.";

/** Строка должна НАЧИНАТЬСЯ с вердикта: цитата внутри фразы — не решение. */
const СТРОКА = /^[\s*_`>#-]*ВЕРДИКТ[\s*_`]*:\s*(.+)$/iu;

export function parseVerdict(текст: string | undefined): Verdict {
  if (!текст) return "missing";
  let итог: Verdict = "missing";
  for (const строка of текст.split(/\r?\n/)) {
    const м = СТРОКА.exec(строка);
    if (!м?.[1]) continue;
    const значение = м[1].replace(/[*_`]/g, "").toUpperCase();
    // Отрицание проверяется раньше согласия: «НЕ ПРИНЯТО» содержит «ПРИНЯТ».
    if (/ЗАМЕЧАН|НЕ\s+ПРИНЯТ/u.test(значение)) итог = "remarks";
    else if (/ПРИНЯТ/u.test(значение)) итог = "accepted";
    else итог = "missing";
  }
  return итог;
}
